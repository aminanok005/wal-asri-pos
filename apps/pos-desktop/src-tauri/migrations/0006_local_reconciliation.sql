-- ============================================================================
-- MIGRATION 0006 — local audit logs and reconciliation flag
-- ============================================================================
--
-- WHAT THIS ADDS
--
-- One table, `local_audit_logs`, for every local state change that should be
-- visible to an operator (conflict flag changes, void requests, etc.).
--
-- The `requires_reconcile` column on `stock_balances` marks a row that has a
-- cloud‑side newer snapshot and local unsynced movement (local dirty), so the
-- terminal can lock the stock count and prevent its deduction until the
-- operator resolves the conflict.
--
-- ── The audit log ────────────────────────────────────────────────────────────
-- The primary key is a UUIDv7 generated by the client (same reason as
-- `local_orders.id`). `entity_type` and `entity_id` identify the row in the
-- source table; `action` is the operation that caused the log (`create`,
-- `update`, `delete`, `reconcile`, `void`, `resolve_conflict`, etc.).
--
-- `old_value_json` and `new_value_json` hold the full row state **as JSON**
-- before and after the change. This is a simple audit trail; no complex
-- parsing required, and it is exactly what the outbox stores for `payload`.
--
-- `reason` gives a short human‑readable label (e.g., "cloud_local_mismatch",
-- "user_resolved").
--
-- `actor_terminal_id` is the terminal that made the change (nullable for
-- system actions). Stored as TEXT — the same UUIDv7 format as the row’s
-- own `id`, so a log entry belongs to a specific terminal.
--
-- ── The reconciliation flag ─────────────────────────────────────────────────
-- `requires_reconcile` is an INTEGER 0/1 column on `stock_balances`. When a
-- newer server snapshot arrives and the local row is dirty (has unsynced
-- movement), we set this flag to 1 and write an audit log. The flag is cleared
-- by the `resolve_stock_conflict` command after the operator has taken the
-- corrective action, and the resolved quantity is stored in
-- `conflict_cloud_quantity_milli`.
--
-- ── Schema details ───────────────────────────────────────────────────────────
-- The primary key is `id TEXT PRIMARY KEY`.
--
-- CHECK constraints:
--   * `entity_type IN ('order','stock_balance','refund','sync','void_request')`
--   * `action IN ('create','update','delete','reconcile','void','resolve_conflict')`
--
-- Indexes:
--   * idx_local_audit_logs_entity   (entity_type, entity_id)
--   * idx_local_audit_logs_created    (created_at)

CREATE TABLE local_audit_logs (
  id TEXT PRIMARY KEY,
  entity_type TEXT NOT NULL CHECK (entity_type IN ('order','stock_balance','refund','sync','void_request')),
  entity_id TEXT NOT NULL,
  action TEXT NOT NULL CHECK (action IN ('create','update','delete','reconcile','void','resolve_conflict')),
  old_value_json TEXT,
  new_value_json TEXT,
  reason TEXT,
  actor_terminal_id TEXT,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);

CREATE INDEX idx_local_audit_logs_entity ON local_audit_logs(entity_type, entity_id);
CREATE INDEX idx_local_audit_logs_created ON local_audit_logs(created_at);

ALTER TABLE stock_balances ADD COLUMN requires_reconcile INTEGER NOT NULL DEFAULT 0;
CREATE INDEX idx_stock_balances_reconcile ON stock_balances(requires_reconcile) WHERE requires_reconcile = 1;

PRAGMA user_version = 6;
